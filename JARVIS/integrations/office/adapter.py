"""
JARVIS AI - Document & Report Generation Adapter
Creates formatted summary reports, attendance documents, and source research comparisons.
"""

from pathlib import Path
from typing import Dict, Any, List, Optional
import time


class OfficeDocumentAdapter:
    def __init__(self, output_dir: Optional[str] = None):
        if not output_dir:
            output_dir = str(Path(__file__).resolve().parent.parent.parent / "workspaces" / "reports")
        self.output_dir = Path(output_dir).resolve()
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def generate_attendance_report(self, analysis_result: Dict[str, Any], output_filename: str = "monthly_attendance_report.md") -> Dict[str, Any]:
        """
        Creates a structured Markdown report from attendance analysis data.
        """
        report_path = self.output_dir / output_filename
        total = analysis_result.get("total_individuals", 0)
        overall_avg = analysis_result.get("overall_attendance_average", 0.0)
        below_count = analysis_result.get("below_75_percent_count", 0)
        below_list = analysis_result.get("below_75_percent_list", [])

        lines = [
            "# Monthly Attendance Summary & Analytics Report",
            f"**Generated by:** JARVIS AI Digital Operator",
            f"**Date:** {time.strftime('%Y-%m-%d %H:%M:%S')}",
            "",
            "## 1. Executive Summary",
            f"- **Total Individuals Analyzed:** {total}",
            f"- **Overall Class/Team Average Attendance:** {overall_avg}%",
            f"- **Individuals with Low Attendance (< 75%):** {below_count}",
            "",
            "## 2. Low Attendance Flagged Individuals",
        ]

        if below_list:
            lines.append("| Name | Total Days | Present | Absent | Attendance % |")
            lines.append("|---|---|---|---|---|")
            for item in below_list:
                lines.append(f"| {item['name']} | {item['total_days']} | {item['present_days']} | {item['absent_days']} | {item['attendance_percentage']}% |")
        else:
            lines.append("*(No individuals are below the 75% threshold. All records compliant.)*")

        lines.extend([
            "",
            "## 3. Recommended Actions",
            "- Dispatch notifications to individuals flagged under 75% attendance.",
            "- Sync report with academic / management portal.",
            "",
            "---",
            "*Report verified and generated via JARVIS local automation.*"
        ])

        content = "\n".join(lines)
        report_path.write_text(content, encoding="utf-8")

        return {
            "success": True,
            "report_path": str(report_path),
            "filename": output_filename,
            "bytes": len(content.encode("utf-8")),
            "verified": report_path.exists() and report_path.stat().st_size > 0
        }

    def generate_research_report(
        self,
        topic: str,
        sources: List[Dict[str, str]],
        summary: str,
        output_filename: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Creates a formatted research document comparing sources on a topic.
        """
        clean_topic = "".join(c for c in topic if c.isalnum() or c in (' ', '_', '-')).strip()
        filename = output_filename or f"research_{clean_topic.replace(' ', '_').lower()}.md"
        report_path = self.output_dir / filename

        lines = [
            f"# Research Dossier: {topic}",
            f"**Compiled by:** JARVIS AI Personal Assistant",
            f"**Timestamp:** {time.strftime('%Y-%m-%d %H:%M:%S')}",
            "",
            "## Executive Synthesis",
            summary,
            "",
            "## Source Evaluation & Comparison",
            "| Source Name | Reliability / Key Findings | Reference |",
            "|---|---|---|"
        ]

        for s in sources:
            name = s.get("name", "Unknown Source")
            findings = s.get("findings", "N/A")
            ref = s.get("url", s.get("ref", "N/A"))
            lines.append(f"| {name} | {findings} | {ref} |")

        lines.extend([
            "",
            "---",
            "*Document produced by JARVIS autonomous research workflow.*"
        ])

        content = "\n".join(lines)
        report_path.write_text(content, encoding="utf-8")

        return {
            "success": True,
            "report_path": str(report_path),
            "filename": filename,
            "bytes": len(content.encode("utf-8")),
            "verified": report_path.exists()
        }
